-- Lista de compras inteligente: catálogo base de produtos e o perfil de cada Casa.

-- Produtos comuns, para a Casa que ainda não tem histórico. chave é o nome normalizado
-- (sem acento, minúsculo, singular simples), calculado pela mesma regra de NomeProduto.chave.
create table produto_comum (
    chave  varchar(160) primary key,
    nome   varchar(160) not null,
    lugar  varchar(20) not null,     -- GELADEIRA, FREEZER, ARMARIO, LIMPEZA ou HIGIENE
    basico boolean not null          -- sugerido mesmo sem histórico
);

-- O que a Casa tem, compra e recusa. É daqui que sai a pontuação de cada produto.
create table produto_casa (
    id               uuid primary key,
    casa_id          uuid not null references casa (id),
    chave            varchar(160) not null,
    nome             varchar(160) not null,
    lugar            varchar(20),
    vezes_visto      integer not null,
    vezes_adicionado integer not null,
    vezes_comprado   integer not null,
    vezes_recusado   integer not null,
    ignorado         boolean not null,
    ultima_vez       timestamp with time zone not null,
    unique (casa_id, chave)
);

